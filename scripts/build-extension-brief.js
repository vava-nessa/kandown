#!/usr/bin/env node
/**
 * @file Extension agent brief generator
 * @description Builds the machine-facing plugin authoring brief from the
 * extension type contract, so the text an AI agent reads can never drift from
 * the code it must compile against. Signatures, event names and field types are
 * lifted verbatim out of `src/lib/extensions/types.ts`; the surrounding prose
 * (the loop, the failure table, the worked examples) lives in this script.
 *
 * Two artefacts come out of one render:
 *   - `docs/EXTENSIONS-AGENT.md`, the human/repo-visible copy;
 *   - `src/lib/extensions/agent-brief.ts`, the same text as a TS constant so
 *     `kandown plugin create` can print it from the published bundle, which
 *     ships `dist/` only and never carries `docs/`.
 *
 * Run `pnpm extension-brief` after touching the extension types, or
 * `pnpm extension-brief:check` (wired into `pnpm verify` and CI) to fail on
 * drift.
 *
 * @functions
 *  → extractBlock — pull one `export interface|type` declaration out of a source
 *  → extractUnion — pull the string-literal union of a named method parameter
 *  → renderBrief — assemble the full markdown brief
 *  → main — write both artefacts, or compare them under `--check`
 * @see src/cli/lib/plugin-cli.ts
 * @see docs/EXTENSIONS-AUTHORING.md
 */

import { readFileSync, writeFileSync } from 'node:fs';
import { join, dirname } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = join(dirname(fileURLToPath(import.meta.url)), '..');
const TYPES_PATH = join(root, 'src', 'lib', 'extensions', 'types.ts');
const MD_OUT = join(root, 'docs', 'EXTENSIONS-AGENT.md');
const TS_OUT = join(root, 'src', 'lib', 'extensions', 'agent-brief.ts');

/**
 * 📖 Pulls one top-level declaration out of a TypeScript source by brace
 * matching. Deliberately not a parser: the extension contract is a flat file of
 * plain interfaces, and a 20-line matcher that fails loudly beats a dependency.
 */
function extractBlock(source, name) {
  const patterns = [
    new RegExp(`^export interface ${name}(?: extends [^{]+)?\\s*\\{`, 'm'),
    new RegExp(`^export type ${name}\\s*=`, 'm'),
  ];
  for (const pattern of patterns) {
    const match = pattern.exec(source);
    if (!match) continue;
    const start = match.index;
    if (match[0].endsWith('{')) {
      let depth = 0;
      for (let i = start; i < source.length; i++) {
        if (source[i] === '{') depth++;
        else if (source[i] === '}') {
          depth--;
          if (depth === 0) return source.slice(start, i + 1);
        }
      }
    } else {
      const end = source.indexOf(';', start);
      if (end !== -1) return source.slice(start, end + 1);
    }
  }
  throw new Error(`build-extension-brief: could not extract "${name}" from types.ts`);
}

/** Strips comments and blank lines so a signature block stays scannable. */
function terse(block) {
  return block
    .split('\n')
    .filter((line) => {
      const t = line.trim();
      return t && !t.startsWith('//') && !t.startsWith('*') && !t.startsWith('/*');
    })
    .join('\n');
}

/**
 * 📖 Reads the string-literal union of a declaration, e.g. the `on:` field of
 * `GateContribution` or the first parameter of `KandownExtensionAPI.on`. The
 * event names in the brief are therefore always the ones the host dispatches.
 */
function extractUnion(block, label) {
  const match = new RegExp(`${label}\\s*:\\s*((?:'[^']+'\\s*\\|\\s*)*'[^']+')`).exec(block.replace(/\n\s*/g, ' '));
  if (!match) throw new Error(`build-extension-brief: no string union for "${label}"`);
  return match[1].split('|').map((part) => part.trim().replace(/'/g, ''));
}

function renderBrief() {
  const types = readFileSync(TYPES_PATH, 'utf8');

  const fieldType = extractBlock(types, 'FieldType');
  const api = extractBlock(types, 'KandownExtensionAPI');
  const context = extractBlock(types, 'ExtensionContext');
  const gate = extractBlock(types, 'GateContribution');
  const sync = extractBlock(types, 'SyncContribution');
  const field = extractBlock(types, 'FieldContribution');
  const panel = extractBlock(types, 'WebPanelContribution');
  const command = extractBlock(types, 'CommandContribution');
  const verdict = extractBlock(types, 'GateVerdict');
  const taskLike = extractBlock(types, 'TaskLike');

  const fieldTypes = fieldType.split('=')[1].replace(';', '').split('|').map((t) => t.trim().replace(/'/g, ''));
  const gateEvents = extractUnion(gate, 'on');
  const syncEvents = extractUnion(sync, 'on');
  const lifecycleEvents = extractUnion(api, 'on\\(event');

  return `# Kandown plugin brief (for coding agents)

<!-- Generated by scripts/build-extension-brief.js from src/lib/extensions/types.ts.
     Do not edit by hand: run \`pnpm extension-brief\`. -->

You are writing a **kandown plugin**. This document is the complete contract.
Everything below is extracted from the shipped type definitions, so it matches
the runtime you will be loaded into. Read it once, write the code, then run the
loop at the bottom until it is green.

## 1. What a plugin is

A directory under \`.kandown/extensions/<id>/\` containing:

| File | Required | Purpose |
|---|---|---|
| \`manifest.json\` | yes | identity, permissions, display hints |
| \`index.ts\` | yes | the Node entry, loaded with jiti (no build step in dev) |
| \`index.js\` | to ship | bundled entry, the only thing the browser can execute |
| \`web.tsx\` / \`web.js\` | panels only | the panel module, bundled the same way |
| \`README.md\` | no | human documentation |

\`index.ts\` default-exports a factory. It is called once at load, it registers
contributions, and it must not do slow or throwing work at module scope.

\`\`\`typescript
import type { KandownExtensionAPI } from 'kandown';

export default function (kd: KandownExtensionAPI) {
  // register here
}
\`\`\`

## 2. The API you are handed

\`\`\`typescript
${terse(api)}
\`\`\`

Contribution shapes, verbatim:

\`\`\`typescript
${terse(field)}

${terse(panel)}

${terse(command)}

${terse(gate)}

${terse(sync)}

${terse(verdict)}
\`\`\`

## 3. The context handlers receive

\`\`\`typescript
${terse(context)}

${terse(taskLike)}
\`\`\`

\`ctx.fetch\` is present **only** when a \`net:\` permission is declared. \`ctx.board\`
throws without \`read:tasks\`. \`ctx.setField\` throws without
\`write:field:plugins.<id>.<key>\` (a trailing \`*\` covers every key).

## 4. Events

| Kind | Names | Semantics |
|---|---|---|
| Gates (\`contributeGate\`) | ${gateEvents.map((e) => `\`${e}\``).join(', ')} | may veto by returning \`{ block: true, reason }\`; a throw is treated as no objection |
| Syncs (\`contributeSync\`) | ${syncEvents.map((e) => `\`${e}\``).join(', ')} | fire and forget, after the file is written |
| Lifecycle (\`kd.on\`) | ${lifecycleEvents.map((e) => `\`${e}\``).join(', ')} | observation only, never blocks |

Both gates and syncs accept an optional \`to\` to restrict them to one target
column. A move is allowed only when **every** gate abstains or permits.

## 5. Field types

${fieldTypes.map((t) => `\`${t}\``).join(', ')}. Scalars are persisted as strings and coerced back on read,
so a \`number\` field reads back as a number. A \`select\` field must declare
\`options: [{ value, label }]\`, and a value outside that list is rejected.

## 6. Where your data lives

Only under \`plugins.<id>.*\` in the task frontmatter, opaque to the core:

\`\`\`yaml
---
title: Ship the thing
status: Done
plugins:
  my-plugin:
    points: 5
---
\`\`\`

Read it from \`event.task.plugins\`, write it with \`ctx.setField(taskId, key, value)\`.
**Never** write a core field (\`title\`, \`status\`, \`depends_on\`, \`created\`, ...),
never write a second file, never call the serializer.

## 7. Permissions

| Declare | Unlocks |
|---|---|
| \`read:tasks\` | \`ctx.board.readAll()\`, \`ctx.board.read(id)\` |
| \`write:field:plugins.<id>.*\` | \`ctx.setField(...)\` for your namespace |
| \`net:*\` or \`net:<url-prefix>\` | \`ctx.fetch\` |
| \`*\` | everything, avoid it |

Undeclared calls throw at runtime. Declare exactly what you use, nothing more:
\`kandown plugin check\` reports both missing and unused permissions.

## 8. Web panels

Declare the panel in \`index.ts\`, implement it in \`web.tsx\`:

\`\`\`typescript
kd.contributeWebPanel({ id: 'chart', title: 'Burndown', entry: './web.js' });
\`\`\`

\`\`\`javascript
function Chart({ task, api, ui }) {
  const [tasks, setTasks] = ui.useState([]);
  ui.useEffect(() => { void api.readAllTasks().then(setTasks); }, [api]);
  return ui.createElement('div', null, tasks.length + ' tasks');
}

export const panels = { chart: Chart };
\`\`\`

Hard rules for panel modules:

- **Never import React.** The host React runtime arrives as the \`ui\` prop
  (\`ui.createElement\`, \`ui.useState\`, \`ui.useEffect\`, \`ui.Fragment\`). A second
  React copy in the bundle breaks hooks.
- The module must be self-contained: it is imported through a Blob URL and
  cannot resolve sibling files. \`kandown plugin build\` bundles it for you.
- Props are exactly \`{ task, api, ui }\` where \`api\` is
  \`{ readField(key), readAllTasks(), setField(key, value), refresh() }\`.
- Three consecutive render failures quarantine the plugin.

## 9. The build and verify loop

\`\`\`bash
kandown plugin build <id>          # index.ts -> index.js, web.tsx -> web.js
kandown plugin check <id> --json   # structured verdict, exit code 1 on failure
kandown plugin enable <id>         # trust + enable
kandown plugin dev <id>            # watch: rebuild, recheck, hot reload the web UI
\`\`\`

\`check --json\` returns \`{ ok, id, checks: [{ id, status, message, fix }] }\`.
Read \`fix\` on any failing check, apply it, run again. Do not stop until \`ok\`
is \`true\`.

## 10. Failure table

| Symptom from \`plugin check\` | Fix |
|---|---|
| \`manifest\` invalid id | id must match \`^[a-z][a-z0-9-]{0,63}$\` |
| \`entry\` default export is not a function | export the factory as \`export default function (kd) {}\` |
| \`permissions\` missing | add the exact permission string the check names to \`manifest.json\` |
| \`bundle\` missing index.js | run \`kandown plugin build <id>\` |
| \`panel\` module exports nothing | export \`panels\` (a map) or a \`default\` component |
| \`panel\` imports react | drop the import, use the \`ui\` prop |
| \`namespace\` write outside plugins.\\<id\\> | only \`ctx.setField\` may write, and only your own keys |
| \`roundtrip\` frontmatter drift | store plain JSON values, no class instances, no \`undefined\` |
| quarantined | fix the throw, then \`kandown plugin enable <id>\` clears the counter |

## 11. Style rules for this codebase

- Never use an em dash or an en dash in any string, comment or document you write.
- Comment the why, not the what, and open explanatory comments with \`📖\`.
- Keep the factory synchronous unless you genuinely need to await something.
- Handle your own errors: a throw inside a gate is silently fail-open, which
  hides bugs. Log with \`ctx.log.warn\` instead of throwing.
`;
}

function main() {
  const check = process.argv.includes('--check');
  const brief = renderBrief();
  const tsSource = `/**
 * @file Generated plugin authoring brief
 * @description The machine-facing plugin brief, emitted by
 * \`scripts/build-extension-brief.js\` from the extension type contract and
 * embedded here so \`kandown plugin create\` can print it from the published
 * bundle. Do not edit by hand: run \`pnpm extension-brief\`.
 *
 * @exports EXTENSION_AGENT_BRIEF
 * @see scripts/build-extension-brief.js
 * @see docs/EXTENSIONS-AGENT.md
 */

/* eslint-disable */
export const EXTENSION_AGENT_BRIEF: string = ${JSON.stringify(brief)};
`;

  if (check) {
    let drift = false;
    for (const [path, expected] of [[MD_OUT, brief], [TS_OUT, tsSource]]) {
      let actual = '';
      try {
        actual = readFileSync(path, 'utf8');
      } catch {
        actual = '';
      }
      if (actual !== expected) {
        console.error(`✗ ${path} is out of date. Run: pnpm extension-brief`);
        drift = true;
      }
    }
    if (drift) process.exit(1);
    console.log('✓ extension agent brief is up to date');
    return;
  }

  writeFileSync(MD_OUT, brief, 'utf8');
  writeFileSync(TS_OUT, tsSource, 'utf8');
  console.log(`✓ wrote ${MD_OUT}`);
  console.log(`✓ wrote ${TS_OUT}`);
}

main();
