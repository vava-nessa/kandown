#!/usr/bin/env node
/**
 * @file Changelog index generator
 * @description Rebuilds the root `CHANGELOG.md` from the per-version files in
 * `changelogs/`. The index is a table of contents — version, date, codename and
 * a per-type change count — with a link to each full file.
 *
 * 📖 Why the split. One 800-line changelog is unreviewable in a diff: every
 * release touches the top of the same file, so every release conflicts with
 * every other in-flight branch, and `git log -p CHANGELOG.md` is unreadable.
 * One file per version means a release adds a file instead of editing a shared
 * one, and a link to `changelogs/v0.36.1.md` is stable and guessable forever.
 *
 * 📖 Why the index is generated. It is derived data — every field in it already
 * exists in the version files. A hand-maintained index drifts the first time
 * someone ships a release in a hurry, and a stale table of contents is worse
 * than none because it looks authoritative. Same reasoning, and the same
 * pre-commit hook, as `CODEMAP.md`.
 *
 * 📖 Run via: `pnpm changelog` (write) or `pnpm changelog:check` (verify).
 * The pre-commit hook runs the write mode and stages the result; CI runs
 * `--check` and fails on drift.
 *
 * 📖 Ordering is by semver descending, computed numerically — the filenames
 * sort lexically wrong (`v0.9.0` after `v0.36.0`) and that is fine, because
 * nothing but this script depends on the directory order. `unreleased.md`, when
 * present, is always pinned above every released version.
 *
 * @functions
 *  → parseVersionFile — one changelogs/*.md → its heading fields + change counts
 *  → compareVersions — numeric semver descending comparator
 *  → buildIndex — the rendered CHANGELOG.md string
 *
 * @see docs/RELEASE.md — the release procedure that adds a version file
 */

import { readFileSync, writeFileSync, readdirSync, existsSync } from 'node:fs';
import { join, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

const PKG_ROOT = resolve(fileURLToPath(new URL('.', import.meta.url)), '..');
const DIR = join(PKG_ROOT, 'changelogs');
const OUT = join(PKG_ROOT, 'CHANGELOG.md');

/** 📖 Accepts legacy headings with U+2014 and new headings with plain hyphens. */
const RE_TITLE = /^#\s+(Unreleased|\d+\.\d+\.\d+)(?:\s+(?:\u2014|-)\s+(\d{4}-\d{2}-\d{2}))?\s+(?:\u2014|-)\s+"(.+)"\s*$/;

/** 📖 The change-type sections, in the order they are displayed. */
const TYPES = ['Added', 'Fixed', 'Changed', 'Removed', 'Cleaned'];

/**
 * 📖 Reads one version file into the fields the index needs.
 *
 * Change counts are best-effort: the modern format groups bullets under
 * `## Added` / `## Fixed` headings, while releases up to 0.13 used a flat list
 * of `- **Added**: …` bullets. Both are counted, so the index stays informative
 * across the whole history instead of showing zeros for everything old.
 */
function parseVersionFile(filename) {
  const text = readFileSync(join(DIR, filename), 'utf8');
  const lines = text.split('\n');
  const title = lines.find(line => line.startsWith('# '));
  const match = title ? title.match(RE_TITLE) : null;
  if (!match) {
    throw new Error(
      `changelogs/${filename}: first heading must look like ` +
      `'# 0.36.1 - 2026-07-26 - "Name"', got ${title ? `'${title}'` : 'no H1'}`
    );
  }
  const [, version, date, name] = match;

  const counts = Object.fromEntries(TYPES.map(type => [type, 0]));
  let section = null;
  for (const line of lines) {
    const heading = line.match(/^##\s+(\w+)/);
    if (heading) {
      section = TYPES.includes(heading[1]) ? heading[1] : null;
      continue;
    }
    if (!line.startsWith('- ')) continue;
    // 📖 Legacy flat format: the type is inline on the bullet itself.
    const inline = line.match(/^- \*\*(\w+)\*\*:/);
    if (inline && TYPES.includes(inline[1])) { counts[inline[1]]++; continue; }
    if (section) counts[section]++;
  }

  return { filename, version, date: date ?? null, name, counts };
}

/** 📖 Newest first, comparing each numeric segment — not the string. */
function compareVersions(a, b) {
  if (a.version === 'Unreleased') return -1;
  if (b.version === 'Unreleased') return 1;
  const pa = a.version.split('.').map(Number);
  const pb = b.version.split('.').map(Number);
  for (let i = 0; i < 3; i++) {
    if (pa[i] !== pb[i]) return pb[i] - pa[i];
  }
  return 0;
}

/** 📖 `3 added · 1 fixed` — empty string when a release has no counted bullets. */
function summarize(counts) {
  return TYPES
    .filter(type => counts[type] > 0)
    .map(type => `${counts[type]} ${type.toLowerCase()}`)
    .join(' · ');
}

function buildIndex(entries) {
  const out = [
    '# Changelog',
    '',
    '<!-- Generated by `pnpm changelog` from ./changelogs/ — do not edit by hand. -->',
    '',
    'Every release has its own file in [`changelogs/`](changelogs/). This page is',
    'the index; click a version for the full notes.',
    '',
  ];

  const unreleased = entries.find(entry => entry.version === 'Unreleased');
  if (unreleased) {
    const summary = summarize(unreleased.counts);
    out.push(
      '## Unreleased',
      '',
      `**[${unreleased.name}](changelogs/unreleased.md)**${summary ? ` — ${summary}` : ''}`,
      '',
    );
  }

  const released = entries.filter(entry => entry.version !== 'Unreleased');
  // 📖 Grouped by year so the table stays scannable as the history grows.
  const years = [...new Set(released.map(entry => (entry.date ?? '____').slice(0, 4)))];
  for (const year of years) {
    const rows = released.filter(entry => (entry.date ?? '____').slice(0, 4) === year);
    out.push(`## ${year}`, '', '| Version | Date | Release | Changes |', '|---|---|---|---|');
    for (const entry of rows) {
      out.push(
        `| [${entry.version}](changelogs/${entry.filename}) ` +
        `| ${entry.date ?? '—'} | ${entry.name} | ${summarize(entry.counts) || '—'} |`
      );
    }
    out.push('');
  }

  return out.join('\n').replace(/\n{3,}/g, '\n\n').trimEnd() + '\n';
}

// ─── Main ────────────────────────────────────────────────────────────────────

if (!existsSync(DIR)) {
  console.error(`changelog: ${DIR} not found`);
  process.exit(1);
}

const files = readdirSync(DIR).filter(name => name.endsWith('.md'));
const entries = files.map(parseVersionFile).sort(compareVersions);
const index = buildIndex(entries);

const check = process.argv.includes('--check');
const existing = existsSync(OUT) ? readFileSync(OUT, 'utf8') : '';

if (check) {
  if (existing !== index) {
    console.error('✗ CHANGELOG.md is stale — run `pnpm changelog` and commit the result.');
    process.exit(1);
  }
  console.log(`✓ CHANGELOG.md up to date (${entries.length} releases)`);
} else {
  if (existing !== index) writeFileSync(OUT, index, 'utf8');
  console.log(`changelog: indexed ${entries.length} releases from changelogs/`);
}
